#!/usr/bin/env python3
"""Import pinned upstream fixtures, or verify the offline corpus without network access."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import shutil
import subprocess


ROOT = Path(__file__).resolve().parent.parent / 'tests/upstream'
SOURCES = {
    'alacritty': ('https://github.com/alacritty/alacritty',
                  '94e7c8874e526b1e67b349d9ba30ddf81669119e'),
    'libvterm': ('https://github.com/neovim/libvterm',
                '934bc2fbf21800ac3458a499df8820ca5fb45fd3'),
}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def import_corpus(args):
    entries = []
    counts = {}
    for name, (url, revision) in SOURCES.items():
        source = getattr(args, name).resolve(strict=True)
        actual = subprocess.check_output(['git', '-C', source, 'rev-parse', 'HEAD'], text=True).strip()
        if actual != revision:
            raise ValueError(f'{name}: expected revision {revision}, got {actual}')
        if name == 'alacritty':
            cases = sorted((source / 'alacritty_terminal/tests/ref').iterdir())
            files = [file for case in cases for file in sorted(case.iterdir())]
            files += [source / 'LICENSE-APACHE', source / 'LICENSE-MIT']
            counts[name] = len(cases)
        else:
            files = sorted((source / 't').glob('90vttest_*.test'))
            counts[name] = len(files)
            files += [source / 'LICENSE']
        destination = ROOT / name
        if destination.exists():
            shutil.rmtree(destination)
        for file in files:
            relative = file.relative_to(source)
            # Gzip is lossless; expected screens and recordings are never regenerated by Tide.
            compressed = name == 'alacritty' and file.name in {
                'alacritty.recording', 'config.json', 'grid.json', 'size.json'}
            target = destination / relative
            raw = file.read_bytes()
            stored = gzip.compress(raw, mtime=0) if compressed else raw
            if compressed:
                target = target.with_name(target.name + '.gz')
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(stored)
            entries.append({'project': name, 'source_path': str(relative),
                            'path': str(target.relative_to(ROOT)), 'gzip': compressed,
                            'bytes': len(raw), 'sha256': digest(raw), 'stored_sha256': digest(stored)})
    manifest = {'schema': 1, 'sources': {name: {'url': url, 'revision': rev}
                for name, (url, rev) in SOURCES.items()}, 'cases': counts, 'files': entries}
    (ROOT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')


def verify():
    manifest = json.loads((ROOT / 'manifest.json').read_text())
    expected_sources = {name: {'url': url, 'revision': rev} for name, (url, rev) in SOURCES.items()}
    if manifest['schema'] != 1 or manifest['sources'] != expected_sources:
        raise ValueError('Manifest source pins differ from the importer')
    seen = set()
    for item in manifest['files']:
        relative = Path(item['path'])
        if relative.is_absolute() or '..' in relative.parts or str(relative) in seen:
            raise ValueError(f'Invalid or duplicate fixture path: {relative}')
        seen.add(str(relative))
        stored = (ROOT / relative).read_bytes()
        raw = gzip.decompress(stored) if item['gzip'] else stored
        if (digest(stored) != item['stored_sha256'] or digest(raw) != item['sha256']
                or len(raw) != item['bytes']):
            raise ValueError(f'Fixture integrity failed: {relative}')
    actual = {str(file.relative_to(ROOT)) for name in SOURCES
              for file in (ROOT / name).rglob('*') if file.is_file()}
    if actual != seen:
        raise ValueError(f'Unregistered or missing files: {actual ^ seen}')
    print(json.dumps({'status': 'passed', 'cases': manifest['cases'], 'files': len(seen)}))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='action', required=True)
    sub.add_parser('verify')
    ingest = sub.add_parser('import')
    for name in SOURCES:
        ingest.add_argument('--' + name, type=Path, required=True)
    args = parser.parse_args()
    if args.action == 'import':
        import_corpus(args)
    verify()


if __name__ == '__main__':
    main()
